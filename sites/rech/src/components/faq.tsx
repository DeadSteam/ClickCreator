/*
  Вопросы в конце письма.

  Не аккордеон и не список с плюсами, а расшифровка разговора: вопрос набран
  серифом курсивом от чужого лица, ответ - обычным текстом от автора. Это
  единственная форма, совместимая с жанром: письмо не складывает свои абзацы
  в закрывающиеся ящики, а человек, отвечающий на вопрос, не прячет ответ за
  щелчком.

  Практическое следствие: компонент серверный, в браузер не уезжает ни грамма
  JavaScript, и весь текст ответов попадает в поисковую выдачу, а не только в
  разметку FAQ. Событие faq_open отсутствует за отсутствием раскрытия -
  интерес меряется глубиной прокрутки, она считается в Boot.

  Тире перед вопросом набрано настоящим длинным тире реплики, как в прямой
  речи в книге: именно оно превращает список в диалог.
*/
export function Faq({ items }: { items: readonly { q: string; a: string }[] }) {
  return (
    <div className="flex flex-col gap-10">
      {items.map((item) => (
        <div key={item.q}>
          <p className="flex gap-3 font-[family-name:var(--font-display)] text-[21px] leading-snug italic sm:text-[23px]">
            <span aria-hidden className="text-[var(--color-ochre)]">
              &mdash;
            </span>
            <span>{item.q}</span>
          </p>

          {/*
            Ответ отбит слева ровно на ширину тире с пробелом, чтобы реплики
            стояли в одной колонке и разговор читался сверху вниз, а не
            распадался на пары.
          */}
          <p className="mt-3 max-w-[62ch] pl-[1.9rem] text-[17px] leading-relaxed text-[var(--color-ink-soft)]">
            {item.a}
          </p>
        </div>
      ))}
    </div>
  );
}
