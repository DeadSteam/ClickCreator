/* Объёмная скидка. Пороги показаны на странице целиком: скрытая скидка
   работает как приманка, показанная - как повод нарастить объём. */
export const TIERS = [
  { from: 500, off: 0.22 },
  { from: 250, off: 0.15 },
  { from: 100, off: 0.08 },
  { from: 0, off: 0 },
] as const;

export const discountFor = (phrases: number) =>
  TIERS.find((t) => phrases >= t.from)?.off ?? 0;

/** Следующий порог скидки или null, если объём уже максимальный. */
export function nextTier(phrases: number) {
  const ordered = [...TIERS].sort((a, b) => a.from - b.from);
  return ordered.find((t) => t.from > phrases) ?? null;
}

