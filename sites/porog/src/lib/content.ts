export type GateResult = {
  verdict: Verdict;
  title: string;
  body: string;
  /* Что предлагаем дальше. У отказа это не кнопка регистрации. */
  action: "register" | "check" | "none";
};

/**
 * Вердикт по допуску.
 *
 * Порядок проверок важен: сначала отсекающие условия, потом смягчающие.
 * Если сначала спросить про трафик, сайт вне ТОП-50 с хорошим трафиком
 * получит допуск, которого не должен получать.
 */
export function verdictFor(a: Partial<Record<Question["id"], string>>): GateResult | null {
  if (!a.top50 || !a.age || !a.traffic) return null;

  if (a.top50 === "нет") {
    return {
      verdict: "отказ",
      title: "Мы вам откажем",
      body: "Сайта нет в первой полусотне по этим запросам, а значит, усиливать нечего: поведенческие сигналы двигают позицию, но не создают её с нуля. Сначала нужна техническая оптимизация и контент. Возьмём деньги сейчас - потратим их впустую, и это будет наша вина, а не ваша.",
      action: "none",
    };
  }

  if (a.age === "молодой") {
    return {
      verdict: "отказ",
      title: "Мы вам откажем",
      body: "Домену меньше трёх месяцев. У поисковика нет истории вашего сайта, поэтому любой нехарактерный всплеск поведения читается на нём отчётливее всего. Мы не беремся за такие проекты - риск ложится на вас, а зарабатываем мы. Возвращайтесь, когда домену исполнится хотя бы полгода.",
      action: "none",
    };
  }

  if (a.top50 === "незнаю") {
    return {
      verdict: "проверим",
      title: "Сначала проверим позиции",
      body: "Заведите проект и добавьте список фраз: кабинет снимет текущие позиции и покажет, какие из них в первой полусотне, а какие нет. Проверка идёт до пополнения баланса, платить за неё не нужно. Если в допуск не проходит ни одна фраза, мы так и напишем.",
      action: "check",
    };
  }

  if (a.traffic === "нет") {
    return {
      verdict: "проверим",
      title: "Допуск с оговоркой",
      body: "Сайт в допуске, но собственного трафика из поиска у него почти нет. Это значит, что подаваемые сессии составят заметную долю всего трафика, и работать придётся на пониженной скорости - экономный режим вместо ускоренного. Рост будет медленнее, зато сигналы не будут выделяться на общем фоне.",
      action: "register",
    };
  }

  return {
    verdict: "допуск",
    title: "Сайт проходит по допуску",
    body: "Позиции в рабочем диапазоне, домен зрелый, собственный трафик есть - подаваемые сессии растворятся в нём. Можно заводить проект и запускать. Первые семь суток идут без привязки карты, а остановить подачу можно в любой момент - она прекращается в течение часа.",
    action: "register",
  };
}

