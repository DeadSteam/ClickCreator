import type { MetadataRoute } from "next";

import { SITE_ORIGIN } from "@/site";

/*
  robots.txt. До сих пор его не было вовсе, и на каждый запрос робота сервер
  отвечал 404 — а вместе с ним не отдавалась и ссылка на карту сайта.

  Запрет ровно один — `/api/`: там нет страниц, только обработчики форм.

  `/privacy` и `/terms` закрыты от индексации мета-тегом в самих страницах, и
  это осознанно не продублировано здесь. `Disallow` и `noindex` — не одно и то
  же: первый запрещает читать страницу, второй — показывать её в выдаче.
  Запретив чтение, мы лишили бы робота возможности увидеть `noindex`, и адрес,
  на который откуда-нибудь стоит ссылка, всё равно попал бы в выдачу — пустой
  строкой без описания.
*/
export default function robots(): MetadataRoute.Robots {
  return {
    rules: {
      userAgent: "*",
      allow: "/",
      disallow: "/api/",
    },
    sitemap: `${SITE_ORIGIN}/sitemap.xml`,
  };
}
