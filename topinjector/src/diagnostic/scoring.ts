/**
 * Балл одного вопроса. У множественного выбора баллы суммируются, но результат
 * зажат в диапазон от нуля до максимума одного варианта: в третьем вопросе есть
 * отрицательные веса, и без нижней границы «позиции + трафик» дали бы минус
 * пять, вычтя риск из других вопросов.
 */
function scoreQuestion(q: Question, picked: string[]): number {
  const sum = picked.reduce((acc, id) => {
    const a = q.answers.find((x) => x.id === id);
    return acc + (a ? a.score : 0);
  }, 0);

  if (!q.multiple) return Math.max(0, sum);

  const cap = Math.max(...q.answers.map((a) => a.score));
  return Math.min(cap, Math.max(0, sum));
}

function maxFor(q: Question): number {
  const positives = q.answers.map((a) => a.score).filter((s) => s > 0);
  return positives.length ? Math.max(...positives) : 0;
}

export type Result = {
  /** Индекс окна сомнения, 0-100. */
  index: number;
  segment: SegmentId;
  /** Подиндексы в шкале 0-100. */
  sub: Record<RiskId, number>;
  /** Подиндекс с максимальным значением — основной риск. */
  risk: RiskId;
  /** Выбранные желания из вопроса 12. */
  goals: string[];
};

export function calculate(answers: Answers): Result {
  const scored = QUESTIONS.filter((q) => q.scored);

  const raw = scored.reduce(
    (acc, q) => acc + scoreQuestion(q, answers[q.id] ?? []),
    0,
  );
  const max = scored.reduce((acc, q) => acc + maxFor(q), 0);

  const index = Math.round((raw / max) * 100);

  const sub = SUBINDEXES.reduce(
    (acc, s) => {
      const qs = scored.filter((q) => s.questions.includes(q.id));
      const got = qs.reduce((n, q) => n + scoreQuestion(q, answers[q.id] ?? []), 0);
      const cap = qs.reduce((n, q) => n + maxFor(q), 0);
      acc[s.id] = cap ? Math.round((got / cap) * 100) : 0;
      return acc;
    },
    {} as Record<RiskId, number>,
  );

  /*
    При равенстве подиндексов побеждает первый по порядку ТЗ. Порядок не
    случайный: раннее недоверие описывает саму суть окна сомнения, поэтому оно
    и должно становиться вердиктом в спорном случае.
  */
  const risk = SUBINDEXES.reduce<RiskId>(
    (best, s) => (sub[s.id] > sub[best] ? s.id : best),
    SUBINDEXES[0].id,
  );

  return {
    index,
    segment: segmentFor(index),
    sub,
    risk,
    goals: answers.goal ?? [],
  };
}

export function segmentFor(index: number): SegmentId {
  if (index <= 24) return "low";
  if (index <= 49) return "medium";
  if (index <= 74) return "high";
  return "critical";
}

/** Параметры для персонализации первого блока «Истории открытия» (п.19 ТЗ). */
export function handoffQuery(r: Result): string {
  const params = new URLSearchParams({
    score: String(r.index),
    segment: r.segment,
    risk: r.risk,
  });
  if (r.goals.length) params.set("goal", r.goals[0]);
  return params.toString();
}
