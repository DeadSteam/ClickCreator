/*
  Токены движения.

  Кривые и длительности были выписаны по месту: одна и та же
  `[0.23, 1, 0.32, 1]` встречалась в тринадцати файлах, а рядом жила почти
  такая же `[0.32, 0.72, 0, 1]`. Разница между ними не была решением — она была
  следом порядка, в котором писались компоненты, и правка «ускорить появление»
  требовала обойти девять файлов и угадать, где какая.

  Значения не выдуманы: EASE_OUT и EASE_HAPTIC совпадают с `--ease-out` и
  `--ease-haptic` из globals.css. CSS и JS анимируют одни и те же элементы, и
  расхождение кривых заметно на переходах, где участвуют оба.
*/

/** Затухание к концу. Появление блоков, счётчики, схемы. */
export const EASE_OUT = [0.23, 1, 0.32, 1] as const;

/** Резче на входе. Панели, оверлеи, всё, что перекрывает страницу. */
export const EASE_HAPTIC = [0.32, 0.72, 0, 1] as const;

/*
  Три скорости появления, а не произвольные числа в каждом вызове.

  QUICK — плотные сетки: карточки, ячейки, шаги. Их много на экране, и любая
  задержка выше трети секунды читается как медленный интерфейс.
  CALM — крупные блоки страницы: один объект в поле зрения, ему можно дать
  время.
  READING — статья: появление не должно обгонять чтение.
*/
export const APPEAR = {
  quick: { duration: 0.32, y: 14, margin: "-60px" },
  calm: { duration: 0.55, y: 14, margin: "-15%" },
  reading: { duration: 0.3, y: 16, margin: "-80px" },
} as const;

export type AppearSpeed = keyof typeof APPEAR;
