/**
 * Поднимает карточку, отвечающую заявленному желанию, на первое место.
 * Остальные сохраняют исходный порядок: перетасовывать весь блок ради одного
 * совпадения значило бы ломать выстроенную логику чтения.
 */
export function orderOutcomes(goal?: string): Card[] {
  if (!goal) return OUTCOMES;
  const hit = OUTCOMES.find((c) => c.id === goal);
  if (!hit) return OUTCOMES;
  return [hit, ...OUTCOMES.filter((c) => c !== hit)];
}

/** Параметры диагностики, которые уходят в каждое событие аналитики. */
export function personalParams(params: {
  score?: string;
  segment?: string;
  risk?: string;
  goal?: string;
}): Record<string, string> {
  const out: Record<string, string> = {};
  if (params.score) out.diagnostic_index = params.score;
  if (params.segment) out.diagnostic_segment = params.segment;
  if (params.risk) out.diagnostic_risk = params.risk;
  if (params.goal) out.diagnostic_goal = params.goal;
  return out;
}
