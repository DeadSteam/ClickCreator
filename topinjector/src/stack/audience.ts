const AUDIENCE_COPY: Record<string, AudienceCopy> = {
  [COMPETITOR_COMMUNITIES]: COMPETITOR_COMMUNITIES_COPY,
};

export type ResolvedAudience = {
  /**
   * Исходное значение `?audience=` без нормализации — разд. 24.17 требует
   * сохранить его для диагностики даже когда копии под него нет. `null`,
   * если параметра не было (разд. 24.16 — стандартный лендинг).
   */
  raw: string | null;
  /** Копия аудитории. `null` и при отсутствии параметра, и при неизвестном значении: в обоих случаях показывается standard experience. */
  copy: AudienceCopy | null;
};

/**
 * Разрешает `?audience=` в набор supporting-копий. Отсутствующее значение и
 * неизвестное значение ведут к одному и тому же результату на экране —
 * стандартному лендингу без технической ошибки и без надписи «unknown
 * audience» (разд. 24.16/24.17). Различаются они только в аналитике, где
 * исходная строка сохраняется как есть.
 */
export function resolveAudience(raw: string | undefined | null): ResolvedAudience {
  const value = typeof raw === "string" && raw.trim() !== "" ? raw.trim() : null;
  return { raw: value, copy: value ? (AUDIENCE_COPY[value] ?? null) : null };
}

export type AudienceHero = {
  supporting: string;
  /** Итоговая надпись на кнопке Hero: оверрайд аудитории либо CTA самого `angle`. */
  cta: string;
  /** Микрокопия под кнопкой Hero или `null`, если аудитория её не меняет. */
  micro: string | null;
};

/**
 * Собирает Hero-копию под пару (audience, angle). Hero по-прежнему выбирается
 * по `angle` — audience только добавляет строку контекста и, для трёх angle из
 * разд. 24.5, свои CTA и microcopy. `null` означает «показать стандартный
 * Hero», а не ошибку.
 */
export function audienceHero(
  audience: ResolvedAudience,
  variant: HeroVariant,
): AudienceHero | null {
  const copy = audience.copy;
  if (!copy) return null;

  const override = copy.heroByAngle[variant.angle];
  return {
    supporting: override?.supporting ?? copy.heroSupporting,
    cta: override?.cta ?? variant.cta,
    micro: override?.micro ?? null,
  };
}
